import assert from 'node:assert/strict'
import { parseStudentsCsv } from '../lib/school/student-import.ts'
let checks = 0
const parse = value => { checks++; return parseStudentsCsv(value) }
let result = parse('dni,nombres,apellidos\n00123456,María José,Muñoz Pérez\n')
assert.equal(result.issues.length, 0)
assert.equal(result.students[0].dni, '00123456')
assert.equal(result.students[0].first_names, 'María José')
result = parse('\uFEFFDNI;NOMBRES;APELLIDOS\r\n12345678;Ana;Pérez\r\n\r\n')
assert.equal(result.issues.length, 0)
result = parse('apellidos\tdni\tnombres\nPérez\t12345678\tAna')
assert.equal(result.issues.length, 0)
result = parse('dni,nombres,apellidos\n12345678,"Ana, María","O\'Connor"')
assert.equal(result.issues.length, 0)
assert.equal(result.students[0].first_names, 'Ana, María')
assert.ok(parse('dni,nombres,apellidos\n1234567,Ana,Pérez').issues.some(i => i.row === 2 && i.message.includes('DNI')))
assert.ok(parse('dni,nombres,apellidos\n,Ana,Pérez').issues.length)
assert.ok(parse('dni,nombres,apellidos\n12345678,Ana,Pérez\n12345678,Luis,Ramos').issues.some(i => i.row === 3 && i.message.includes('repetido')))
assert.ok(parse('dni,nombres,apellidos\n12345678,,Pérez').issues.length)
assert.ok(parse('dni,nombres,apellidos\n12345678,Ana,').issues.length)
assert.ok(parse('dni,nombres,apellidos\n12345678,Ana,Pérez,extra').issues.length)
assert.ok(parse('dni,dni,nombres,apellidos\n12345678,12345678,Ana,Pérez').issues.length)
assert.ok(parse('dni,nombre,apellido\n12345678,Ana,Pérez').issues.length)
assert.ok(parse('dni,nombres,apellidos\n12345678,"Ana,Pérez').issues.length)
assert.ok(parse('').issues.length)
assert.ok(parse('dni,nombres,apellidos\n').issues.length)
assert.ok(parse('dni,nombres,apellidos\n12345678,' + 'A'.repeat(101) + ',Pérez').issues.length)
const rows = Array.from({length:500}, (_,i) => `${String(i).padStart(8,'0')},Ana,Pérez`).join('\n')
assert.equal(parse('dni,nombres,apellidos\n' + rows).issues.length, 0)
assert.ok(parse('dni,nombres,apellidos\n' + rows + '\n99999999,Ana,Pérez').issues.some(i => i.message.includes('máximo')))
assert.equal(parse('dni;nombres;apellidos\n\n12345678;José;García\n;;\n').students.length, 1)
console.log(`${checks} CSV import checks passed`)
