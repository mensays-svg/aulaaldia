import assert from 'node:assert/strict'
import { parseStudentsCsv, classroomKey } from '../lib/school/student-import.ts'
const header = 'dni,nombres,apellidos,año,nivel,grado,sección\n'
const row = '00123456,María José,Muñoz Pérez,2026,Primaria,1,A'
let checks = 0
const parse = value => { checks++; return parseStudentsCsv(value) }
let result = parse(header + row)
assert.equal(result.issues.length, 0)
assert.equal(result.students[0].dni, '00123456')
assert.equal(result.students[0].first_names, 'María José')
assert.equal(result.students[0].academic_year, 2026)
result = parse('\uFEFFDNI;NOMBRES;APELLIDOS;AÑO;NIVEL;GRADO;SECCIÓN\r\n12345678;Ana;Pérez;2026;primaria;1.º;a\r\n\r\n')
assert.equal(result.issues.length, 0)
assert.equal(result.students[0].grade, '1')
assert.equal(result.students[0].section, 'A')
result = parse('seccion\tapellidos\tdni\tnombres\tanio\tgrado\tnivel\nA\tPérez\t12345678\tAna\t2026\tprimero\tprimaria')
assert.equal(result.issues.length, 0)
result = parse(header + '12345678,"Ana, María","O\'Connor",2026,Secundaria,5,B')
assert.equal(result.issues.length, 0)
assert.equal(result.students[0].first_names, 'Ana, María')
assert.ok(parse(header + row.replace('00123456','1234567')).issues.some(i => i.row === 2 && i.message.includes('DNI')))
assert.ok(parse(header + row.replace('00123456','')).issues.length)
assert.ok(parse(header + row + '\n' + row).issues.some(i => i.row === 3 && i.message.includes('repetido')))
assert.ok(parse(header + row.replace('María José','')).issues.length)
assert.ok(parse(header + row.replace('Muñoz Pérez','')).issues.length)
assert.ok(parse(header + row + ',extra').issues.length)
assert.ok(parse('dni,dni,nombres,apellidos,año,nivel,grado,sección\n' + row).issues.length)
assert.ok(parse('dni,nombres,apellidos\n12345678,Ana,Pérez').issues.length)
assert.ok(parse(header + '12345678,"Ana,Pérez,2026,Primaria,1,A').issues.length)
assert.ok(parse('').issues.length)
assert.ok(parse(header).issues.length)
assert.ok(parse(header + row.replace('María José', 'A'.repeat(101))).issues.length)
assert.ok(parse(header + row.replace('2026','26')).issues.some(i => i.message.includes('año')))
assert.ok(parse(header + row.replace('Primaria','Universidad')).issues.length)
assert.ok(parse(header + row.replace('Primaria,1','Secundaria,6')).issues.some(i => i.message.includes('grado')))
assert.ok(parse(header + row.replace('Primaria,1','Inicial,1')).issues.length)
assert.equal(parse(header + row.replace('Primaria,1','Inicial,3 años')).issues.length, 0)
assert.ok(parse(header + row.replace(',A', ',')).issues.some(i => i.message.includes('sección')))
const rows = Array.from({length:500}, (_,i) => `${String(i).padStart(8,'0')},Ana,Pérez,2026,Primaria,1,A`).join('\n')
assert.equal(parse(header + rows).issues.length, 0)
assert.ok(parse(header + rows + '\n99999999,Ana,Pérez,2026,Primaria,1,A').issues.some(i => i.message.includes('máximo')))
result=parse(header + row + '\n' + row.replace('00123456','00123457').replace('Primaria,1,A','Secundaria,2,B'))
assert.equal(result.issues.length, 0)
assert.notEqual(classroomKey(result.students[0]),classroomKey(result.students[1]))
assert.equal(classroomKey({academic_year:2026,level:'Primaria',grade:'primero',section:'a'}),classroomKey(result.students[0]))
console.log(`${checks} unified CSV checks passed`)
